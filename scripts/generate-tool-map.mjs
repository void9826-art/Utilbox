/**
 * Regenerates src/tools/index.tsx from the registry.
 *
 * The loader map has to contain literal import paths so the bundler can split
 * each tool into its own chunk, which rules out building it dynamically at
 * runtime. Generating it keeps it in step with the registry instead.
 */
import fs from "node:fs";

const CATEGORIES = ["pdf", "calculators", "image", "converters", "generators", "text", "developer"];

const entries = [];
for (const category of CATEGORIES) {
  const src = fs.readFileSync(`src/config/tools/${category}.ts`, "utf8");
  for (const match of src.matchAll(/^\s{4}slug: "([a-z0-9-]+)",$/gm)) {
    entries.push({ category, slug: match[1] });
  }
}

// Tools whose component has not been written yet are skipped so the project
// still typechecks mid-build. validate-registry.mjs fails the build if any are
// still missing.
const missing = entries.filter(
  ({ category, slug }) => !fs.existsSync(`src/tools/${category}/${slug}.tsx`),
);
if (missing.length > 0) {
  console.warn(`WARNING: ${missing.length} tool component(s) not yet written:`);
  for (const { category, slug } of missing) console.warn(`  - ${category}/${slug}`);
}
const present = entries.filter(
  ({ category, slug }) => fs.existsSync(`src/tools/${category}/${slug}.tsx`),
);

const lines = present
  .map(
    ({ category, slug }) =>
      `  "${slug}": dynamic(() => import("./${category}/${slug}"), { loading: Loading }),`,
  )
  .join("\n");

const file = `"use client";

// Generated by scripts/generate-tool-map.mjs — do not edit by hand.
// Run \`npm run generate:tools\` after adding a tool to the registry.

import dynamic from "next/dynamic";
import type { ComponentType } from "react";

import { ToolSkeleton } from "@/components/tool/tool-frame";

const Loading = () => <ToolSkeleton />;

/**
 * Every tool is a separate lazily-loaded chunk, so visiting one tool page never
 * downloads the code for the other ${entries.length - 1}.
 */
const TOOL_COMPONENTS: Record<string, ComponentType> = {
${lines}
};

export function ToolMount({ slug }: { slug: string }) {
  const Component = TOOL_COMPONENTS[slug];
  if (!Component) return null;
  return <Component />;
}

export function hasToolComponent(slug: string): boolean {
  return slug in TOOL_COMPONENTS;
}
`;

fs.mkdirSync("src/tools", { recursive: true });
fs.writeFileSync("src/tools/index.tsx", file, "utf8");
console.log(`Wrote src/tools/index.tsx with ${entries.length} tools.`);
